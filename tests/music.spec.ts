import { test, expect, type Page } from '@playwright/test'
import { fileURLToPath } from 'node:url'

const songPath = fileURLToPath(new URL('../public/demo/soft-focus.wav', import.meta.url))
const uploadInput = (page: Page) => page.getByLabel('Choose audio files', { exact: true })
const songRows = (page: Page) => page.locator('.track-row')
const ownSong = (page: Page) => songRows(page).filter({ hasText: 'soft-focus' })
const demoSong = (page: Page) => songRows(page).filter({ hasText: 'Soft Focus' })

async function uploadSong(page: Page) {
  await uploadInput(page).setInputFiles(songPath)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your library.')
  await expect(ownSong(page)).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Add your music', exact: true })).not.toBeVisible()
}

async function setRange(page: Page, label: string, value: number) {
  await page.getByRole('slider', { name: label, exact: true }).evaluate((element, target) => {
    const input = element as HTMLInputElement
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, String(target))
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  }, value)
}

async function setSeek(page: Page, seconds: number) {
  await setRange(page, 'Seek playback', seconds)
}

test('decodes demo audio, advances time, seeks, pauses and operates the queue', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await demoSong(page).getByRole('button', { name: 'Play Soft Focus by media originals', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible()
  const seek = page.getByRole('slider', { name: 'Seek playback', exact: true })
  await expect(seek).toHaveAttribute('max', '22')
  await expect.poll(async () => Number(await seek.inputValue())).toBeGreaterThan(0.4)
  await setSeek(page, 10)
  await expect.poll(async () => Number(await seek.inputValue())).toBeGreaterThanOrEqual(10)
  await page.getByRole('button', { name: 'Pause playback', exact: true }).click()
  const pausedAt = Number(await seek.inputValue())
  await expect(page.getByRole('button', { name: 'Start playback', exact: true })).toBeVisible()
  await page.waitForTimeout(650)
  expect(Number(await seek.inputValue())).toBeCloseTo(pausedAt, 1)
  await page.getByRole('button', { name: 'Next song', exact: true }).click()
  await expect(page.locator('.now-playing-info strong')).toHaveText('Blue Hour')
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Repeat: off', exact: true }).click()
  await page.getByRole('button', { name: 'Repeat: all', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Repeat: one', exact: true })).toBeVisible()
  await setSeek(page, 21.7)
  await expect.poll(async () => Number(await seek.inputValue())).toBeLessThan(3)
  await expect(page.locator('.now-playing-info strong')).toHaveText('Blue Hour')
  await page.getByRole('button', { name: 'Shuffle', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Shuffle', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Show play queue', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Play queue', exact: true }).locator('.queue-track')).toHaveCount(3)
  await page.getByRole('button', { name: 'Mute', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Unmute', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

