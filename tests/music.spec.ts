import { test, expect, type Page } from '@playwright/test'
import { fileURLToPath } from 'node:url'

const songPath = fileURLToPath(new URL('../public/demo/soft-focus.wav', import.meta.url))
const uploadInput = (page: Page) => page.getByLabel('Choose audio files', { exact: true })
const songRows = (page: Page) => page.locator('.track-row')
const ownSong = (page: Page) => songRows(page).filter({ hasText: 'soft-focus' })

async function uploadSong(page: Page) {
  await uploadInput(page).setInputFiles(songPath)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your library.')
  await expect(ownSong(page)).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Add your music', exact: true })).not.toBeVisible()
}

async function setSeek(page: Page, seconds: number) {
  await page.getByRole('slider', { name: 'Seek playback', exact: true }).evaluate((element, target) => {
    const input = element as HTMLInputElement
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, String(target))
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  }, seconds)
}

test('decodes demo audio, advances time, seeks, pauses and operates the queue', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.locator('.album-card').first().getByRole('button', { name: 'Play Soft Focus', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible()
  const seek = page.getByRole('slider', { name: 'Seek playback', exact: true })
  await expect(seek).toHaveAttribute('max', '22')
  await expect.poll(async () => Number(await seek.inputValue())).toBeGreaterThan(0.4)
  await setSeek(page, 10)
  await expect.poll(async () => Number(await seek.inputValue())).toBeGreaterThanOrEqual(10)
  await page.getByRole('button', { name: 'Pause playback', exact: true }).click()
  const pausedAt = Number(await seek.inputValue())
  await expect(page.getByRole('button', { name: 'Start playback', exact: true })).toBeVisible()
  await page.waitForTimeout(650)
  expect(Number(await seek.inputValue())).toBeCloseTo(pausedAt, 1)
  await page.getByRole('button', { name: 'Next song', exact: true }).click()
  await expect(page.locator('.now-playing-info strong')).toHaveText('Blue Hour')
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Repeat: off', exact: true }).click()
  await page.getByRole('button', { name: 'Repeat: all', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Repeat: one', exact: true })).toBeVisible()
  await setSeek(page, 21.7)
  await expect.poll(async () => Number(await seek.inputValue())).toBeLessThan(3)
  await expect(page.locator('.now-playing-info strong')).toHaveText('Blue Hour')
  await page.getByRole('button', { name: 'Shuffle', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Shuffle', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Show play queue', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Play queue', exact: true }).locator('.queue-track')).toHaveCount(3)
  await page.getByRole('button', { name: 'Mute', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Unmute', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('persists uploaded audio, favorites and playlists, then removes the original safely', async ({ page }) => {
  await page.goto('/')
  await uploadSong(page)
  await expect(ownSong(page).locator('.time-column')).toHaveText('0:22')
  await ownSong(page).getByRole('button', { name: 'Play soft-focus', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible()
  await expect.poll(async () => Number(await page.getByLabel('Seek playback').inputValue())).toBeGreaterThan(0.2)
  await ownSong(page).getByRole('button', { name: 'Favorite soft-focus', exact: true }).click()
  await expect(ownSong(page).getByRole('button', { name: 'Unfavorite soft-focus', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Create playlist', exact: true }).click()
  const create = page.getByRole('dialog', { name: 'Create a playlist', exact: true })
  await create.getByLabel('Playlist name', { exact: true }).fill('Slow Sundays')
  await create.getByRole('button', { name: 'Create playlist', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Slow Sundays.')
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: /^Your library/ }).click()
  await ownSong(page).getByRole('button', { name: 'More options for soft-focus', exact: true }).click()
  await page.getByRole('button', { name: 'Add to playlist', exact: true }).click()
  await page.getByRole('dialog', { name: 'Add to playlist', exact: true }).getByRole('button', { name: /Slow Sundays/ }).click()
  await page.getByRole('button', { name: 'Slow Sundays', exact: true }).click()
  await expect(ownSong(page)).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Slow Sundays', exact: true }).click()
  await expect(ownSong(page)).toBeVisible()
  await expect(ownSong(page).getByRole('button', { name: 'Unfavorite soft-focus', exact: true })).toBeVisible()
  await ownSong(page).getByRole('button', { name: 'Play soft-focus', exact: true }).click()
  await expect.poll(async () => Number(await page.getByLabel('Seek playback').inputValue())).toBeGreaterThan(0.2)
  await ownSong(page).getByRole('button', { name: 'More options for soft-focus', exact: true }).click()
  await page.getByRole('button', { name: 'Remove from playlist', exact: true }).click()
  await expect(songRows(page)).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: /^Favorites/ }).click()
  await expect(ownSong(page)).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search your music' }).fill('not an existing song')
  await expect(songRows(page)).toHaveCount(0)
  await expect(page.getByText('No songs match', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Clear search', exact: true }).click()
  await ownSong(page).getByRole('button', { name: 'More options for soft-focus', exact: true }).click()
  await page.getByRole('button', { name: 'Remove from library', exact: true }).click()
  await page.getByRole('dialog', { name: 'Remove song', exact: true }).getByRole('button', { name: 'Remove song', exact: true }).click()
  await expect(songRows(page)).toHaveCount(0)
  await expect(page.locator('.now-playing-info strong')).toHaveText('Find your next feeling')
  await expect(page.getByRole('slider', { name: 'Seek playback', exact: true })).toBeDisabled()
  await page.reload()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: /^Your library/ }).click()
  await expect(songRows(page)).toHaveCount(0)
})

test('rejects duplicates and invalid files without losing an existing upload', async ({ page }) => {
  await page.goto('/')
  await uploadSong(page)
  await uploadInput(page).setInputFiles(songPath)
  await expect(page.getByRole('alert')).toContainText('already in your library')
  await expect(songRows(page)).toHaveCount(1)
  await page.getByRole('dialog', { name: 'Add your music', exact: true }).getByRole('button', { name: 'Close dialog', exact: true }).click()
  await uploadInput(page).setInputFiles({ name: 'not-a-song.txt', mimeType: 'text/plain', buffer: Buffer.from('This is not audio.') })
  await expect(page.getByRole('alert')).toContainText('choose an audio file')
  await expect(songRows(page)).toHaveCount(1)
  await page.getByRole('dialog', { name: 'Add your music', exact: true }).getByRole('button', { name: 'Close dialog', exact: true }).click()
  await uploadInput(page).setInputFiles({ name: 'broken.wav', mimeType: 'audio/wav', buffer: Buffer.from('not a valid waveform') })
  await expect(page.getByRole('alert')).toContainText('audio could not be read')
  await expect(songRows(page)).toHaveCount(1)
})

test('mobile navigation, upload and playback fit the screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Listen now.')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Your library', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your library.')
  await expect(page.getByRole('button', { name: 'Close navigation', exact: true })).not.toBeVisible()
  await page.getByRole('button', { name: 'Add your music', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Add your music', exact: true })
  await expect(modal).toBeVisible()
  const box = await modal.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await uploadInput(page).setInputFiles(songPath)
  await expect(ownSong(page)).toBeVisible()
  await ownSong(page).getByRole('button', { name: 'Play soft-focus', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible()
  await expect.poll(async () => Number(await page.getByLabel('Seek playback').inputValue())).toBeGreaterThan(0.2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})


test('drag-and-drop imports valid audio and reports other files independently', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(async () => {
    const audio = await (await fetch('/demo/blue-hour.wav')).blob()
    const dataTransfer = new DataTransfer()
    dataTransfer.items.add(new File([audio], 'Dropped song.wav', { type: 'audio/wav', lastModified: 101 }))
    dataTransfer.items.add(new File(['not audio'], 'My notes.txt', { type: 'text/plain', lastModified: 102 }))
    window.dispatchEvent(new DragEvent('dragenter', { dataTransfer, bubbles: true, cancelable: true }))
    window.dispatchEvent(new DragEvent('drop', { dataTransfer, bubbles: true, cancelable: true }))
  })
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your library.')
  await expect(songRows(page)).toHaveCount(1)
  await expect(songRows(page).first()).toContainText('Dropped song')
  await expect(songRows(page).first().locator('.time-column')).toHaveText('0:22')
  await expect(page.getByRole('alert')).toContainText('My notes.txt: choose an audio file')
  await expect(page.locator('.drag-overlay')).not.toBeVisible()
  await page.reload()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: /^Your library/ }).click()
  await expect(songRows(page)).toHaveCount(1)
  await expect(songRows(page).first()).toContainText('Dropped song')
})
