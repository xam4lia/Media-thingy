test('drag-and-drop imports valid audio and reports other files independently', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(async () => {
    const audio = await (await fetch('/demo/blue-hour.wav')).blob()
    const dataTransfer = new DataTransfer()
    dataTransfer.items.add(new File([audio], 'Dropped song.wav', { type: 'audio/wav', lastModified: 101 }))
    dataTransfer.items.add(new File(['not audio'], 'My notes.txt', { type: 'text/plain', lastModified: 102 }))
    window.dispatchEvent(new DragEvent('dragenter', { dataTransfer, bubbles: true, cancelable: true }))
    window.dispatchEvent(new DragEvent('drop', { dataTransfer, bubbles: true, cancelable: true }))
  })
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your library.')
  await expect(songRows(page)).toHaveCount(1)
  await expect(songRows(page).first()).toContainText('Dropped song')
  await expect(songRows(page).first().locator('.time-column')).toHaveText('0:22')
  await expect(page.getByRole('alert')).toContainText('My notes.txt: choose an audio file')
  await expect(page.locator('.drag-overlay')).not.toBeVisible()
  await page.reload()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: /^Your library/ }).click()
  await expect(songRows(page)).toHaveCount(1)
  await expect(songRows(page).first()).toContainText('Dropped song')
})


